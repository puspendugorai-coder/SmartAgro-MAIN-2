function showTranslationTimerOverlay(langObj, onStartExecution) {
    _ensureTimerOverlayStyles();
    let ov = document.getElementById('txTimerOverlay');
    if (!ov) {
        ov = document.createElement('div');
        ov.id = 'txTimerOverlay';
        ov.className = 'tx-timer-overlay';
        document.body.appendChild(ov);
    }

    const langName = langObj.name || langObj.code || 'Selected Language';
    window._txTimerEstimatedTarget = 2.5;

    ov.innerHTML = `
      <div class="tx-timer-card" style="position:relative">
        <button onclick="document.getElementById('txTimerOverlay').classList.remove('visible')" style="position:absolute;top:10px;right:12px;background:rgba(255,255,255,.1);border:none;color:#fff;width:28px;height:28px;border-radius:50%;cursor:pointer;font-size:1.1rem;display:flex;align-items:center;justify-content:center;transition:background .2s;z-index:1" onmouseover="this.style.background='rgba(248,113,113,.4)'" onmouseout="this.style.background='rgba(255,255,255,.1)'" title="Cancel translation">&times;</button>
        <div class="tx-timer-header"><i class="fas fa-globe"></i> <span>Multilingual Translation</span></div>
        <div class="tx-timer-title">Translating to ${langName}</div>
        <div class="tx-timer-sub">Translating buttons, interface &amp; fetched API data</div>
        
        <div class="tx-digital-clock">
          <span id="txClockTick">0.0</span><span class="total">s / ~<span id="txClockTarget">2.5</span>s</span>
        </div>

        <div class="tx-progress-container">
          <div class="tx-progress-bar-fill" id="txProgressFill"></div>
        </div>

        <div class="tx-status-steps">
          <div class="tx-step-item active" id="txStep1"><i class="fas fa-spinner fa-spin"></i> <span>Translating Buttons &amp; UI Elements</span></div>
          <div class="tx-step-item" id="txStep2"><i class="fas fa-circle"></i> <span>Translating Page Content &amp; Cards</span></div>
          <div class="tx-step-item" id="txStep3"><i class="fas fa-circle"></i> <span>Translating Fetched Weather &amp; API Data</span></div>
        </div>
      </div>`;

    requestAnimationFrame(() => ov.classList.add('visible'));

    const startTime = Date.now();
    let completed = false;

    const timerInterval = setInterval(() => {
        if (completed) return;
        const currentTarget = window._txTimerEstimatedTarget || 2.5;
        const rawElapsed = (Date.now() - startTime) / 1000;
        const displayElapsed = Math.min(currentTarget, rawElapsed);
        const percent = Math.min(95, Math.round((displayElapsed / currentTarget) * 100));

        const tickEl = document.getElementById('txClockTick');
        const targetEl = document.getElementById('txClockTarget');
        const fillEl = document.getElementById('txProgressFill');

        if (tickEl) tickEl.textContent = displayElapsed.toFixed(1);
        if (targetEl) targetEl.textContent = currentTarget.toFixed(1);
        if (fillEl) fillEl.style.width = percent + '%';

        const step1 = document.getElementById('txStep1');
        const step2 = document.getElementById('txStep2');
        const step3 = document.getElementById('txStep3');

        if (percent > 30 && step1 && step2) {
            step1.className = 'tx-step-item done'; step1.querySelector('i').className = 'fas fa-check-circle';
            step2.className = 'tx-step-item active'; step2.querySelector('i').className = 'fas fa-spinner fa-spin';
        }
        if (percent > 65 && step2 && step3) {
            step2.className = 'tx-step-item done'; step2.querySelector('i').className = 'fas fa-check-circle';
            step3.className = 'tx-step-item active'; step3.querySelector('i').className = 'fas fa-spinner fa-spin';
        }
    }, 40);

    const finishOverlay = function() {
        if (completed) return;
        completed = true;
        clearInterval(timerInterval);

        const totalElapsed = Math.max(0.6, (Date.now() - startTime) / 1000);
        const tickEl = document.getElementById('txClockTick');
        const targetEl = document.getElementById('txClockTarget');
        const fillEl = document.getElementById('txProgressFill');
        const step1 = document.getElementById('txStep1');
        const step2 = document.getElementById('txStep2');
        const step3 = document.getElementById('txStep3');

        if (tickEl) tickEl.textContent = totalElapsed.toFixed(1);
        if (targetEl) targetEl.textContent = totalElapsed.toFixed(1);
        if (fillEl) fillEl.style.width = '100%';

        if (step1) { step1.className = 'tx-step-item done'; step1.querySelector('i').className = 'fas fa-check-circle'; }
        if (step2) { step2.className = 'tx-step-item done'; step2.querySelector('i').className = 'fas fa-check-circle'; }
        if (step3) { step3.className = 'tx-step-item done'; step3.querySelector('i').className = 'fas fa-check-circle'; }

        setTimeout(() => {
            ov.classList.remove('visible');
        }, 250);
    };

    // Safety timeout — never hold overlay for more than 4.5 seconds
    setTimeout(() => {
        if (!completed) finishOverlay();
    }, 4500);

    if (typeof onStartExecution === 'function') {
        onStartExecution(finishOverlay);
    }
}

window.changeAppLanguage = function(code) {
    if (!code) return;
    const langObj = LANGUAGES.find(l => l.code === code) || { name: code, label: code.toUpperCase() };

    showTranslationTimerOverlay(langObj, function(finishOverlay) {
        setLanguage(code);

        const promises = [];
        if (typeof loadDashboardTranslations === 'function') promises.push(loadDashboardTranslations(code));
        if (typeof loadDiagnoseTranslations === 'function') promises.push(loadDiagnoseTranslations(code));
        if (typeof loadMarketTranslations === 'function') promises.push(loadMarketTranslations(code));
        if (typeof loadAlertsTranslations === 'function') promises.push(loadAlertsTranslations(code));

        if (window.currentDiagnosisResult && typeof window.translateCurrentDiagnosisResult === 'function') {
            promises.push(window.translateCurrentDiagnosisResult(code));
        }

        Promise.all(promises).then(() => {
            finishOverlay();
        }).catch(() => {
            finishOverlay();
        });
    });
};

function buildLangList(filter = '') {
    const list = document.getElementById('langList');
    if (!list) return;
    const f = filter.toLowerCase();
    const filtered = LANGUAGES.filter(l =>
        l.name.toLowerCase().includes(f) || l.code.toLowerCase().includes(f)
    );
    list.innerHTML = filtered.map(l => `
    <div class="lang-option ${l.code === currentLang ? 'active' : ''}"
         data-code="${l.code}"
         onclick="window.changeAppLanguage('${l.code}'); closeLangDropdown();">
      <span class="lang-flag">${l.flag}</span>
      <span class="lang-name">${l.name}</span>
      <span class="lang-code">${l.label}</span>
    </div>
  `).join('');
}

function closeLangDropdown() {
    const sel = document.getElementById('langSelector');
    if (sel) sel.classList.remove('open');
}

document.addEventListener('DOMContentLoaded', () => {
    buildLangList();
    applyTranslations();
    updateLangUI();

    const btn = document.getElementById('langBtn');
    const sel = document.getElementById('langSelector');
    if (btn && sel) {
        btn.addEventListener('click', e => {
            e.stopPropagation();
            sel.classList.toggle('open');
        });
        document.addEventListener('click', e => {
            if (!sel.contains(e.target)) sel.classList.remove('open');
        });
    }
    const searchEl = document.getElementById('langSearch');
    if (searchEl) {
        searchEl.addEventListener('input', e => buildLangList(e.target.value));
    }
});
